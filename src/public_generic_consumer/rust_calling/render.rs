const CARRIER_HEADER: &str = r#"//! Generated by `semaprax::public_generic_consumer::rust_calling`. Codec for
//! this descriptor's flat owned-`Bytes` leaf sequence: Logical Carrier v1's
//! wire framing as the native adapter implements it -- `[u64
//! leaf_count][per leaf: u64 len][bytes]`, little-endian (see
//! `src/public_generic_abi/native/provider_body.c`'s own codec, which this
//! restates independently rather than trusts). Encoding walks fields in
//! descriptor order. Decoding independently validates leaf count and framing
//! rather than trusting the native call's own reported success -- "result is
//! decoded only after commit and independently validated."

use crate::error::Error;
use crate::types::{Input, Output};

"#;

const CARRIER_BODY: &str = r#"pub(crate) fn encode_input(value: &Input) -> Vec<u8> {
    let leaves: [&[u8]; FIELD_COUNT] = input_leaves(value);
    encode_leaves(&leaves)
}

fn encode_leaves(leaves: &[&[u8]]) -> Vec<u8> {
    let total: usize = 8 + leaves.iter().map(|leaf| 8 + leaf.len()).sum::<usize>();
    let mut out = Vec::with_capacity(total);
    out.extend_from_slice(&(leaves.len() as u64).to_le_bytes());
    for leaf in leaves {
        out.extend_from_slice(&(leaf.len() as u64).to_le_bytes());
        out.extend_from_slice(leaf);
    }
    out
}

pub(crate) fn decode_output(bytes: &[u8]) -> Result<Output, Error> {
    if bytes.len() < 8 {
        return Err(Error::ResultRejected(
            "truncated result carrier: missing leaf count",
        ));
    }
    let mut offset = 0usize;
    let leaf_count = u64::from_le_bytes(bytes[0..8].try_into().unwrap());
    offset += 8;
    if leaf_count != FIELD_COUNT as u64 {
        return Err(Error::ResultRejected(
            "result carrier leaf count does not match the descriptor-declared field count",
        ));
    }
    let mut leaves: Vec<Vec<u8>> = Vec::with_capacity(FIELD_COUNT);
    for _ in 0..FIELD_COUNT {
        if bytes.len() < offset + 8 {
            return Err(Error::ResultRejected(
                "truncated result carrier: missing leaf length",
            ));
        }
        let len = u64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap()) as usize;
        offset += 8;
        if bytes.len() < offset + len {
            return Err(Error::ResultRejected(
                "truncated result carrier: missing leaf payload",
            ));
        }
        leaves.push(bytes[offset..offset + len].to_vec());
        offset += len;
    }
    if offset != bytes.len() {
        return Err(Error::ResultRejected(
            "trailing bytes after the result carrier",
        ));
    }
    output_from_leaves(leaves)
}
"#;

fn input_leaves_fn(input: &RecordShape) -> String {
    let mut out = String::new();
    out.push_str("fn input_leaves(value: &Input) -> [&[u8]; FIELD_COUNT] {\n");
    out.push_str("    [\n");
    for field in &input.fields {
        let _ = writeln!(out, "        value.{}.as_slice(),", field.field_name());
    }
    out.push_str("    ]\n");
    out.push_str("}\n");
    out
}

fn output_from_leaves_fn(output: &RecordShape) -> String {
    let mut out = String::new();
    out.push_str("fn output_from_leaves(leaves: Vec<Vec<u8>>) -> Result<Output, Error> {\n");
    out.push_str("    let mut leaves = leaves.into_iter();\n");
    out.push_str("    Ok(Output {\n");
    for field in &output.fields {
        let _ = writeln!(
            out,
            "        {}: leaves.next().expect(\"FIELD_COUNT leaves were already checked above\"),",
            field.field_name()
        );
    }
    out.push_str("    })\n");
    out.push_str("}\n");
    out
}


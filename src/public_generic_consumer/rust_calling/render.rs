const ERROR_RS: &str = r#"//! Generated by `semaprax::public_generic_consumer::rust_calling`. A closed,
//! machine-checked error identity: every native `spx_pg_status_v1` this ABI
//! version can return maps to exactly one variant here (see `provider`'s
//! private status-mapping functions); nothing parses a native error string.
//!
//! Sticky failure: once `Provider::transform` selects one of these variants
//! as its returned `Err`, a later release/close failure discovered only
//! during `Drop` is reported as secondary evidence (see
//! `secondary_release_note`) and never replaces it -- `Drop` itself never
//! panics.

/// A stable, closed error category.
#[derive(Debug)]
pub enum Error {
    /// Submitted descriptor bytes did not replay this consumer's own
    /// embedded trusted value.
    DescriptorRejected(&'static str),
    /// Submitted provider-binding bytes did not replay this consumer's own
    /// embedded trusted value, or the native provider's own independent
    /// pairing check rejected them.
    ProviderMismatch(&'static str),
    /// The native provider reported a malformed carrier, an illegal
    /// handle-lifecycle transition, or a foreign/stale/wrong-kind handle --
    /// every native rejection this consumer's own safe API cannot itself
    /// have caused by construction.
    CarrierRejected(&'static str),
    /// A carrier bound (leaf count, or a per-leaf/total byte bound) was
    /// reached.
    CapacityExceeded(&'static str),
    /// The bound checked endpoint itself refused or failed, a native
    /// allocation failed, or a native cleanup failure legally became the
    /// terminal status. Carries the raw native status for diagnostics; it is
    /// never the only machine-readable identity, since the variant itself
    /// already closes the category.
    ExecutionFailed(i32),
    /// The exported result carrier failed this consumer's OWN independent
    /// validation (framing, leaf count, or trailing bytes) -- never trusted
    /// merely because the native call itself reported success.
    ResultRejected(&'static str),
}

impl Error {
    /// A release/close failure observed only after a primary outcome (an
    /// `Ok` return, or an already-selected `Err`) was already settled. Never
    /// propagated as a `Result`; printed so it is not silently lost.
    pub(crate) fn secondary_release_note(status: i32) -> String {
        format!(
            "spx-pg-rust-calling-consumer: secondary release/close failure observed after the primary outcome was already settled (native status {status}); the primary outcome is unaffected"
        )
    }
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::DescriptorRejected(reason) => write!(f, "descriptor rejected: {reason}"),
            Self::ProviderMismatch(reason) => write!(f, "provider mismatch: {reason}"),
            Self::CarrierRejected(reason) => write!(f, "carrier rejected: {reason}"),
            Self::CapacityExceeded(reason) => write!(f, "capacity exceeded: {reason}"),
            Self::ExecutionFailed(status) => write!(f, "execution failed: native status {status}"),
            Self::ResultRejected(reason) => write!(f, "result rejected: {reason}"),
        }
    }
}

impl std::error::Error for Error {}
"#;


//! Web Application Projection v1: `semaprax webapp <file>`.
//!
//! Projects one verified module's records, payload-free variants, and pure
//! convention-named functions into a complete, dependency-free full-stack web
//! application: a JSON REST API with file persistence, client and server
//! validation, computed fields, and a browser UI. The compiler emits only
//! `schema.js`; the runtime files are fixed bytes embedded below.
//!
//! The projection executes nothing and grants nothing. The generated server
//! is an ordinary Node program whose authority is whatever its operator
//! gives it. Every admitted expression is translated with SEMAPRAX semantics
//! (checked `i64` arithmetic over BigInt, IEEE `f64`, UTF-8 byte lengths);
//! anything outside the admitted subset fails closed with `SPX-WA103`.
//! [docs/WEBAPP-PROJECTION-V1.md](../docs/WEBAPP-PROJECTION-V1.md) owns the
//! contract.

